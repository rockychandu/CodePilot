"""
Unit tests for CodePilot Pilot AI Assistant Engine
"""

import unittest
from codepilot.ai.pilot_ai_engine import PilotAIEngine


class TestPilotAIEngine(unittest.TestCase):
    def test_complexity_constant(self):
        code = "def add(a, b):\n    return a + b"
        res = PilotAIEngine.estimate_complexity("python", code)
        self.assertEqual(res["time"], "O(1)")

    def test_complexity_linear(self):
        code = "def find_max(arr):\n    m = arr[0]\n    for x in arr:\n        if x > m:\n            m = x\n    return m"
        res = PilotAIEngine.estimate_complexity("python", code)
        self.assertEqual(res["time"], "O(N)")

    def test_complexity_quadratic(self):
        code = "def bubble_sort(arr):\n    for i in range(len(arr)):\n        for j in range(len(arr)-1):\n            if arr[j] > arr[j+1]:\n                arr[j], arr[j+1] = arr[j+1], arr[j]"
        res = PilotAIEngine.estimate_complexity("python", code)
        self.assertEqual(res["time"], "O(N^2)")

    def test_review_clean_python_code(self):
        code = "def square(n: int) -> int:\n    return n * n\n"
        review = PilotAIEngine.review_code(user_id=1, language="python", source_code=code)
        self.assertTrue(review["qualityScore"] >= 80)
        self.assertIn("Pilot AI Code Review", review["output"])

    def test_review_antipattern_bare_except(self):
        code = "try:\n    x = 1 / 0\nexcept:\n    pass\n"
        review = PilotAIEngine.review_code(user_id=1, language="python", source_code=code)
        self.assertTrue(any("bare 'except:'" in s for s in review["suggestions"]))

    def test_generate_unit_tests(self):
        code = "def multiply(x, y):\n    return x * y\n"
        tests = PilotAIEngine.generate_tests(user_id=1, language="python", source_code=code)
        self.assertIn("class TestAutoGenerated", tests["testCode"])
        self.assertIn("test_multiply_base_case", tests["testCode"])

    def test_explain_bug(self):
        diag = PilotAIEngine.explain_bug(1, "python", "x = arr[100]", "IndexError: list index out of range")
        self.assertIn("IndexError", diag["explanation"])
        self.assertTrue(len(diag["suggestedFix"]) > 0)


if __name__ == "__main__":
    unittest.main()
